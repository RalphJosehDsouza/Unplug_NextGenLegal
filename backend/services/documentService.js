import { promises as fs } from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import crypto from 'crypto';
import handlebars from 'handlebars';
import puppeteer from 'puppeteer';
import { S3Client, PutObjectCommand, GetObjectCommand, DeleteObjectCommand } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const templatesDir = path.join(__dirname, '..', 'templates');

const s3 = new S3Client({
  region: process.env.S3_REGION,
  credentials: {
    accessKeyId: process.env.AWS_ACCESS_KEY_ID,
    secretAccessKey: process.env.AWS_SECRET_ACCESS_KEY,
  },
});

async function geminiGenerateHTML(templateName, fields) {
  const apiKey = process.env.GEMINI_API_KEY;
  if (!apiKey) throw new Error('GEMINI_API_KEY is not configured');

  const docType = String(templateName).replace(/_/g, ' ').replace(/\b\w/g, (c) => c.toUpperCase());
  const fieldsSummary = Object.entries(fields || {})
    .map(([k, v]) => `- ${k}: ${v}`)
    .join('\n');

  const systemPrompt = `You are a legal document generator for Indian law. Generate a complete, professional HTML document. Rules:
1. Output ONLY valid HTML (no markdown, no code fences).
2. Use inline CSS for styling — professional fonts, proper margins, legal formatting.
3. Include proper legal headers, sections, signature blocks and date fields.
4. Use the document type and field data provided to fill in all content.
5. Make it look like a real legal document — formal language, numbered clauses, proper structure.
6. Include a "Generated by NextGenLegal" watermark footer.`;

  const userMessage = `Generate a complete "${docType}" legal document with these details:\n${fieldsSummary}\n\nOutput the full HTML document.`;

  const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.0-flash:generateContent?key=${encodeURIComponent(apiKey)}`;

  const resp = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      systemInstruction: { parts: [{ text: systemPrompt }] },
      contents: [{ role: 'user', parts: [{ text: userMessage }] }],
      generationConfig: { maxOutputTokens: 4096, temperature: 0.2 },
    }),
  });

  if (!resp.ok) {
    const text = await resp.text().catch(() => '');
    throw new Error(`Gemini API error (${resp.status})${text ? `: ${text}` : ''}`);
  }

  const data = await resp.json();
  let html = data?.candidates?.[0]?.content?.parts?.map((p) => p?.text).filter(Boolean).join('') || '';

  // Strip markdown code fences if Gemini wraps them
  html = html.replace(/^```html?\s*/i, '').replace(/\s*```\s*$/i, '').trim();

  if (!html) throw new Error('Gemini returned empty HTML');
  return html;
}

export async function generatePDF(templateName, fields) {
  let html;

  // Try loading a Handlebars template first (backward compatible)
  const templatePath = path.join(templatesDir, `${templateName}.hbs`);
  try {
    const templateStr = await fs.readFile(templatePath, 'utf8');
    const template = handlebars.compile(templateStr);
    html = template(fields || {});
  } catch {
    // No template file exists — use Gemini AI to generate HTML dynamically
    console.log(`[documentService] No .hbs template for "${templateName}", using Gemini AI`);
    html = await geminiGenerateHTML(templateName, fields);
  }

  const browser = await puppeteer.launch({
    headless: 'new',
    args: ['--no-sandbox', '--disable-setuid-sandbox'],
  });

  try {
    const page = await browser.newPage();
    await page.setContent(html, { waitUntil: 'networkidle0' });
    const pdfBuffer = await page.pdf({
      format: 'A4',
      printBackground: true,
      margin: {
        top: '2cm',
        bottom: '2cm',
        left: '2cm',
        right: '2cm',
      },
    });
    return pdfBuffer;
  } finally {
    await browser.close();
  }
}

export function encryptBuffer(buffer) {
  const key = crypto.randomBytes(32); // AES-256
  const iv = crypto.randomBytes(16);

  const cipher = crypto.createCipheriv('aes-256-cbc', key, iv);
  const encryptedChunks = [cipher.update(buffer), cipher.final()];
  const ciphertext = Buffer.concat(encryptedChunks);

  // Prepend IV so we can decrypt later.
  const encrypted = Buffer.concat([iv, ciphertext]);

  return {
    encrypted,
    key: key.toString('hex'),
    iv: iv.toString('hex'),
  };
}

function sanitizeFilename(name) {
  return String(name || '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/[^a-zA-Z0-9-_]/g, '')
    .slice(0, 80);
}

export async function uploadToS3(userId, encryptedBuffer, filename) {
  const safeName = sanitizeFilename(filename) || 'document';
  const s3Key = `docs/${userId}/${Date.now()}-${safeName}.pdf.enc`;

  const cmd = new PutObjectCommand({
    Bucket: process.env.S3_BUCKET,
    Key: s3Key,
    Body: encryptedBuffer,
    ContentType: 'application/octet-stream',
  });

  await s3.send(cmd);
  return s3Key;
}

